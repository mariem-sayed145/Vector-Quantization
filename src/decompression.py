"""Image decompression for the Vector Quantization project.

This module consumes the two files generated by ``compress_image``:
- ``codebook.json``: codebook vectors and image metadata.
- ``compressed.txt``: the binary representation of codebook indices.

The file format and index decoding are intentionally reused from
``src.compression`` so both modules stay compatible.
"""

from pathlib import Path

import numpy as np
from PIL import Image

from src.compression import decode_indices, load_codebook


def _validate_metadata(metadata: dict) -> None:
    """Validate the saved metadata and return its dimensions."""

    required_keys = {
        "codebook",
        "original_shape",
        "padded_shape",
        "block_size",
        "codebook_size",
    }
    missing_keys = required_keys.difference(metadata)
    if missing_keys:
        missing = ", ".join(sorted(missing_keys))
        raise ValueError(f"Codebook file is missing metadata: {missing}.")

    codebook = metadata["codebook"]
    if codebook.ndim != 2 or codebook.shape[0] == 0:
        raise ValueError("Codebook must be a non-empty 2D array.")

    if not np.all(np.isfinite(codebook)):
        raise ValueError("Codebook contains invalid numeric values.")

    if len(metadata["original_shape"]) != 3:
        raise ValueError("Original image shape must contain height, width, and channels.")

    if len(metadata["padded_shape"]) != 3:
        raise ValueError("Padded image shape must contain height, width, and channels.")

    if len(metadata["block_size"]) != 2:
        raise ValueError("Block size must contain height and width.")

    height, width, channels = metadata["original_shape"]
    padded_height, padded_width, padded_channels = metadata["padded_shape"]
    block_height, block_width = metadata["block_size"]

    dimensions = (height, width, padded_height, padded_width,
                  channels, padded_channels, block_height, block_width)
    if any(not isinstance(value, int) or value <= 0 for value in dimensions):
        raise ValueError("Image dimensions and block dimensions must be positive integers.")

    if channels != 3 or padded_channels != 3:
        raise ValueError("Only RGB images with 3 color channels are supported.")

    if padded_height % block_height != 0 or padded_width % block_width != 0:
        raise ValueError("Padded image dimensions must be divisible by the block size.")

    expected_padded_height = ((height + block_height - 1) // block_height) * block_height
    expected_padded_width = ((width + block_width - 1) // block_width) * block_width
    if (padded_height, padded_width) != (expected_padded_height, expected_padded_width):
        raise ValueError("Padded image dimensions do not match the original shape and block size.")

    expected_vector_length = block_height * block_width * channels
    if codebook.shape[1] != expected_vector_length:
        raise ValueError(
            "Codebook vector size does not match the saved block size "
            "and RGB channels."
        )

    if metadata["codebook_size"] != len(codebook):
        raise ValueError("Saved codebook_size does not match the number of codebook vectors.")

def reconstruct_image(
    indices: np.ndarray,
    codebook: np.ndarray,
    original_shape: tuple,
    padded_shape: tuple,
    block_size: tuple,
) -> np.ndarray:
    """Rebuild an RGB image from decoded indices and codebook vectors."""

    height, width, channels = original_shape
    padded_height, padded_width, padded_channels = padded_shape
    block_height, block_width = block_size

    if channels != 3 or padded_channels != 3:
        raise ValueError("Only RGB images with 3 color channels are supported.")

    if block_height <= 0 or block_width <= 0:
        raise ValueError("Block dimensions must be positive.")

    if padded_height % block_height or padded_width % block_width:
        raise ValueError("Padded dimensions must be divisible by the block size.")

    expected_blocks = (padded_height // block_height) * (padded_width // block_width)
    if len(indices) != expected_blocks:
        raise ValueError(
            f"Expected {expected_blocks} block indices, but received {len(indices)}."
        )

    expected_vector_length = block_height * block_width * channels
    if codebook.ndim != 2 or codebook.shape[1] != expected_vector_length:
        raise ValueError("Codebook vector dimensions do not match the block size.")

    if np.any(indices < 0) or np.any(indices >= len(codebook)):
        raise ValueError("Compressed stream contains an invalid codebook index.")

    # Replace each encoded index with its corresponding codebook vector.
    blocks = codebook[indices].reshape(
        expected_blocks, block_height, block_width, channels
    )

    # Restore the original 2D arrangement of image blocks.
    blocks_per_row = padded_width // block_width
    block_rows = padded_height // block_height
    image = blocks.reshape(
        block_rows, blocks_per_row, block_height, block_width, channels
    )
    image = image.transpose(0, 2, 1, 3, 4)
    image = image.reshape(padded_height, padded_width, channels)

    # Remove the padding added during compression.
    image = image[:height, :width, :]

    return np.clip(image, 0, 255).astype(np.uint8)


def decompress_image(
    codebook_path: str | Path,
    binary_path: str | Path,
    output_path: str | Path = "data/output/decompressed.png",
) -> dict:
    """Decompress an image using the codebook and binary stream files.

    Args:
        codebook_path: Path to the ``codebook.json`` produced by compression.
        binary_path: Path to the ``compressed.txt`` produced by compression.
        output_path: Destination for the reconstructed RGB image.

    Returns:
        A dictionary containing the output path and useful decompression details.
    """

    codebook_path = Path(codebook_path)
    binary_path = Path(binary_path)
    output_path = Path(output_path)

    if not codebook_path.is_file():
        raise FileNotFoundError(f"Codebook file not found: {codebook_path}")

    if not binary_path.is_file():
        raise FileNotFoundError(f"Compressed binary stream not found: {binary_path}")

    # 1. Load the codebook and the metadata saved by compression.py.
    metadata = load_codebook(codebook_path)
    _validate_metadata(metadata)

    codebook = metadata["codebook"]
    codebook_size = len(codebook)

    # 2. Calculate how many image blocks were encoded.
    padded_height, padded_width = metadata["padded_shape"][:2]
    block_height, block_width = metadata["block_size"]
    number_of_blocks = (
        (padded_height // block_height) * (padded_width // block_width)
    )

    # 3. Read the text-based binary stream created by save_binary_stream().
    try:
        binary_stream = binary_path.read_text(encoding="ascii").strip()
    except UnicodeDecodeError as error:
        raise ValueError("Compressed stream must contain only binary text (0 and 1).") from error

    # 4. Decode the stream into codebook indices.
    indices = decode_indices(
        binary_stream=binary_stream,
        num_indices=number_of_blocks,
        k=codebook_size,
    )

    # Check the optional bit-width metadata as an extra consistency check.
    expected_bits_per_index = max(1, (codebook_size - 1).bit_length())
    saved_bits_per_index = metadata.get("bits_per_index", expected_bits_per_index)
    if saved_bits_per_index != expected_bits_per_index:
        raise ValueError("Saved bits_per_index does not match the codebook size.")

    # 5. Reconstruct the image blocks, combine them, and remove the padding.
    reconstructed_image = reconstruct_image(
        indices=indices,
        codebook=codebook,
        original_shape=metadata["original_shape"],
        padded_shape=metadata["padded_shape"],
        block_size=metadata["block_size"],
    )

    # 6. Save as PNG to preserve the reconstructed pixel values exactly.
    output_path.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(reconstructed_image).save(output_path, format="PNG")

    return {
        "output_path": str(output_path),
        "image_shape": reconstructed_image.shape,
        "num_blocks": number_of_blocks,
        "codebook_size": codebook_size,
        "bits_per_index": expected_bits_per_index,
        "binary_file_size": binary_path.stat().st_size,
        "codebook_file_size": codebook_path.stat().st_size,
    }


